const dictionaries: Record<string, Dictionary> = { en: {}, ru, de, es, fr, ja, ko, th, vn, zh };

let active: Dictionary = dictionaries.en;

/** Locale ids follow the admin panel convention (en, ru, …, vn, zh). */
export function setLocale(locale: string | null | undefined): void {
  const requested = (locale || '').replace('_', '-');
  const base = requested.split('-')[0];
  active = dictionaries[requested] ?? dictionaries[base] ?? dictionaries.en;
}

/** Translate an English source string; {placeholders} are interpolated. */
export function t(key: string, params?: Record<string, string | number>): string {
  let text = active[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
